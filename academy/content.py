# ---------- помощники разметки ----------
def P(*paras):
    return "".join(f"<p>{x}</p>" for x in paras)


def UL(*items):
    return "<ul>" + "".join(f"<li>{x}</li>" for x in items) + "</ul>"


def FORMULA(text):
    return f'<div class="formula-box">{text}</div>'


def QUOTE(text):
    return f'<div class="quote-callout">{text}</div>'


def CMP(bad, good, effect=None):
    eff = f'<div class="compare-effect">{effect}</div>' if effect else ""
    bad_html = f'<div class="compare-bad"><span class="compare-tag">❌</span>{bad}</div>' if bad else ""
    return (f'<div class="compare-row">{bad_html}'
            f'<div class="compare-good"><span class="compare-tag">✅</span>{good}</div>{eff}</div>')


def TABOO(title, text):
    return f'<div class="taboo-card"><b>{title}</b><br>{text}</div>'


def EX(task, answer, label="Показать ответ"):
    return (f'<div class="exercise-card"><p>{task}</p>'
            f'<button class="reveal-btn" data-label="{label}" onclick="app.toggleReveal(this)">{label}</button>'
            f'<div class="reveal-answer">{answer}</div></div>')


def CARD(title, body):
    """Карточка-описание (психотип, ситуация и т.п.) — на базе exercise-card без кнопки."""
    return f'<div class="exercise-card"><p><b>{title}</b></p>{body}</div>'


def Qz(category, question, options, correct, explanation):
    """Вопрос квиза. Варианты перемешиваются стабильно (по тексту вопроса),
    поэтому правильный ответ можно всегда писать первым."""
    import hashlib
    import random
    order = list(range(len(options)))
    random.Random(hashlib.md5(question.encode("utf-8")).hexdigest()).shuffle(order)
    return {"category": category, "question": question, "options": [options[i] for i in order],
            "correct": order.index(correct), "explanation": explanation}


